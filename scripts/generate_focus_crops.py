def main():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    public_dir = os.path.join(base_dir, 'public')
    crops_dir = os.path.join(public_dir, 'crops')
    os.makedirs(crops_dir, exist_ok=True)

    page_dirs = {
        'r7_2': 'pages/r7_2',
        'r7_1': 'pages/r7_1',
        'r6_2': 'pages/r6_2',
        'r6_1': 'pages/r6_1',
        'r8_1': 'pages',
    }

    for exam_id, q_crops in CROPS_DEF.items():
        exam_crop_dir = os.path.join(crops_dir, exam_id)
        os.makedirs(exam_crop_dir, exist_ok=True)
        page_dir_name = page_dirs[exam_id]

        json_path = os.path.join(base_dir, 'src', 'data', 'exams', f'{exam_id}.json')
        questions = json.load(open(json_path))

        print(f'Processing {exam_id}...')
        for q in questions:
            qid = q['id']
            if qid in q_crops:
                page_num, h, w, y, x, label = q_crops[qid]
                src_page_path = os.path.join(public_dir, page_dir_name, f'page_{page_num}.png')
                if not os.path.exists(src_page_path):
                    print(f'Warning: source page {src_page_path} not found!')
                    continue

                out_filename = f'q{qid}_focus.png'
                out_path = os.path.join(exam_crop_dir, out_filename)

                # Crop using sips
                cmd = ['sips', '-c', str(h), str(w), '--cropOffset', str(y), str(x), src_page_path, '-o', out_path]
                subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)

                # Set diagram path on question
                rel_path = f'/crops/{exam_id}/{out_filename}'
                q['diagram'] = rel_path

        with open(json_path, 'w', encoding='utf-8') as f:
            json.dump(questions, f, ensure_ascii=False, indent=2)
        print(f'  Updated {json_path} successfully.')

if __name__ == '__main__':
    main()
